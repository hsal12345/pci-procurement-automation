def get_ai_adapter() -> BaseAIAdapter:
    """Factory creating configured AI adapter based on dynamic runtime manager or environment configuration."""
    try:
        from app.services.ai.runtime_manager import runtime_manager
        return runtime_manager.get_active_adapter()
    except Exception as e:
        logger.warning(f"Error getting adapter from runtime_manager, falling back to static config: {e}")
        provider = (settings.AI_PROVIDER or "mock").lower().strip()
        if provider == "mock" or not settings.AI_API_KEY:
            return MockAIAdapter()
        return OpenAICompatibleAdapter()
